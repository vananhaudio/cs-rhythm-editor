-- Bài còn hiển thị với người đang hỏi (member + chưa ẩn, hoặc là thầy)
create or replace function public.class_post_visible(p_post_id uuid)
returns boolean language sql security definer set search_path = '' stable as $$
  select public.is_class_member() and exists (
    select 1 from public.class_posts p
    where p.id = p_post_id and (p.hidden_at is null or public.is_teacher())
  );
$$;
revoke all on function public.class_post_visible(uuid) from public, anon;
grant execute on function public.class_post_visible(uuid) to authenticated;

create or replace function public.class_post_comments_before_write()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    new.body := btrim(new.body);
    new.hidden_at := null; new.hidden_by := null;
    -- trả lời phải cùng bài
    if new.parent_comment_id is not null and not exists (
      select 1 from public.class_post_comments c where c.id = new.parent_comment_id and c.post_id = new.post_id
    ) then
      raise exception 'parent_comment_id không thuộc bài này' using errcode = '23514';
    end if;
    return new;
  end if;
  new.id                := old.id;
  new.seq               := old.seq;
  new.post_id           := old.post_id;
  new.parent_comment_id := old.parent_comment_id;
  new.author_user_id    := old.author_user_id;
  new.created_at        := old.created_at;
  new.body              := btrim(new.body);
  new.updated_at        := now();
  if not public.is_teacher() then
    new.hidden_at := old.hidden_at;
    new.hidden_by := old.hidden_by;
  end if;
  return new;
end $$;
drop trigger if exists class_post_comments_before_write on public.class_post_comments;
create trigger class_post_comments_before_write before insert or update on public.class_post_comments
  for each row execute function public.class_post_comments_before_write();

