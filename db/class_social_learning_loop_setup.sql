-- 5) Gửi bình luận (kèm tag/đính kèm) trong MỘT giao dịch. SECURITY INVOKER → mọi RLS ở trên
--    vẫn áp đúng người gọi (học sinh gửi tag/đính kèm sẽ bị chặn).
--    p_resources: [{resource_type, resource_id, title_snapshot?, start_seconds?, end_seconds?, excerpt?}]
create or replace function public.class_add_comment(
  p_post_id   uuid,
  p_body      text,
  p_tag_ids   bigint[] default '{}',
  p_resources jsonb    default '[]'::jsonb,
  p_parent_id uuid     default null
)
returns uuid language plpgsql security invoker set search_path = '' as $$
declare v_id uuid; r jsonb; i int := 0;
begin
  insert into public.class_post_comments (post_id, parent_comment_id, body)
  values (p_post_id, p_parent_id, p_body)
  returning id into v_id;

  if coalesce(array_length(p_tag_ids, 1), 0) > 0 then
    if array_length(p_tag_ids, 1) > 10 then raise exception 'Tối đa 10 tag' using errcode = '23514'; end if;
    insert into public.class_comment_tags (comment_id, tag_id)
    select v_id, t from (select distinct unnest(p_tag_ids) as t) x;
  end if;

  if jsonb_typeof(p_resources) = 'array' and jsonb_array_length(p_resources) > 0 then
    if jsonb_array_length(p_resources) > 5 then raise exception 'Tối đa 5 tài nguyên' using errcode = '23514'; end if;
    for r in select * from jsonb_array_elements(p_resources) loop
      insert into public.class_comment_resources (comment_id, resource_type, resource_id, title_snapshot, start_seconds, end_seconds, excerpt, sort_order)
      values (v_id, r->>'resource_type', r->>'resource_id', nullif(btrim(r->>'title_snapshot'), ''),
              nullif(r->>'start_seconds', '')::int, nullif(r->>'end_seconds', '')::int,
              nullif(btrim(r->>'excerpt'), ''), i);
      i := i + 1;
    end loop;
  end if;
  return v_id;
end $$;
revoke all on function public.class_add_comment(uuid, text, bigint[], jsonb, uuid) from public, anon;
grant execute on function public.class_add_comment(uuid, text, bigint[], jsonb, uuid) to authenticated;

-- 6) Kiểm duyệt (ẩn / bỏ ẩn) — CHỈ thầy/admin
create or replace function public.class_moderate(p_kind text, p_id uuid, p_hidden boolean)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_teacher() then raise exception 'Không có quyền' using errcode = '42501'; end if;
  if p_kind = 'post' then
    update public.class_posts set hidden_at = case when p_hidden then now() end,
                                  hidden_by = case when p_hidden then auth.uid() end
     where id = p_id;
  elsif p_kind = 'comment' then
    update public.class_post_comments set hidden_at = case when p_hidden then now() end,
                                          hidden_by = case when p_hidden then auth.uid() end
     where id = p_id;
  else
    raise exception 'p_kind không hợp lệ' using errcode = '22023';
  end if;
  if not found then raise exception 'Không tìm thấy' using errcode = 'P0002'; end if;
end $$;
revoke all on function public.class_moderate(text, uuid, boolean) from public, anon;
grant execute on function public.class_moderate(text, uuid, boolean) to authenticated;

-- 7) Danh tính công khai dùng chung (tên hiển thị + avatar + vai trò) — không email/SĐT
create or replace function public.class_public_identity(p_user_id uuid)
returns table(name text, avatar_url text, role text, ht_member boolean)
language sql security definer set search_path = '' stable as $$
  select coalesce(
           nullif(split_part(trim(s.display_name), '@', 1), ''),
           nullif(split_part(trim(s.full_name), '@', 1), ''),
           nullif(split_part(trim(au.name), '@', 1), ''),
           'Thành viên Class'),
         s.avatar_url,
         case when au.role in ('teacher', 'admin') then 'teacher' else 'student' end,
         coalesce(s.ht_member, false)
  from (select p_user_id as uid) x
  left join lateral (
    select es.display_name, es.full_name, es.avatar_url, es.ht_member
    from public.edu_students es where es.user_id = x.uid
    order by es.enrolled_at desc nulls last limit 1
  ) s on true
  left join public.app_users au on au.id = x.uid;
$$;
revoke all on function public.class_public_identity(uuid) from public, anon, authenticated;  -- chỉ dùng nội bộ RPC

-- 8) Feed: bỏ bài bị ẩn (trừ thầy), thêm is_hidden + comment_count. Đổi kiểu trả về → drop/create.
drop function if exists public.class_feed(timestamptz, uuid, int);
create function public.class_feed(
  p_before    timestamptz default null,
  p_before_id uuid        default null,
  p_limit     int         default 20
)
returns table(
  id uuid, type text, body text,
  media_type text, media_provider text, media_url text, external_media_id text,
  created_at timestamptz, updated_at timestamptz,
  author_user_id uuid, author_name text, author_avatar_url text,
  author_role text, author_ht_member boolean, is_mine boolean,
  is_hidden boolean, comment_count int
)
language sql security definer set search_path = '' stable as $$
  select p.id, p.type, p.body,
         p.media_type, p.media_provider, p.media_url, p.external_media_id,
         p.created_at, p.updated_at,
         p.author_user_id, idn.name, idn.avatar_url, idn.role, idn.ht_member,
         p.author_user_id = auth.uid(),
         p.hidden_at is not null,
         (select count(*)::int from public.class_post_comments c
           where c.post_id = p.id and (c.hidden_at is null or public.is_teacher()))
  from public.class_posts p
  cross join lateral public.class_public_identity(p.author_user_id) idn
  where public.is_class_member()
    and (p.hidden_at is null or public.is_teacher())
    and (
      p_before is null
      or p.created_at < p_before
      or (p.created_at = p_before and p_before_id is not null and p.id < p_before_id)
    )
  order by p.created_at desc, p.id desc
  limit least(greatest(coalesce(p_limit, 20), 1), 50);
$$;
revoke all on function public.class_feed(timestamptz, uuid, int) from public, anon;
grant execute on function public.class_feed(timestamptz, uuid, int) to authenticated;

-- 9) Bình luận của nhiều bài trong MỘT lần gọi (không N+1): kèm danh tính công khai,
--    tag, đính kèm (chỉ tham chiếu). Lấy p_per_post bình luận MỚI NHẤT mỗi bài (feed: 3;
--    "Xem thêm bình luận": tối đa 200), trả về theo thứ tự CŨ → MỚI. Tối đa 50 bài/lần.
drop function if exists public.class_comments_for_posts(uuid[]);
create or replace function public.class_comments_for_posts(p_post_ids uuid[], p_per_post int default 3)
returns table(
  id uuid, post_id uuid, parent_comment_id uuid, body text,
  created_at timestamptz, updated_at timestamptz,
  author_user_id uuid, author_name text, author_avatar_url text, author_role text,
  is_mine boolean, is_hidden boolean, tags jsonb, resources jsonb,
  post_comment_count int     -- tổng bình luận (đang hiển thị) của bài — để hiện "Xem thêm (N)"
)
language sql security definer set search_path = '' stable as $$
  select c.id, c.post_id, c.parent_comment_id, c.body, c.created_at, c.updated_at,
         c.author_user_id, idn.name, idn.avatar_url, idn.role,
         c.author_user_id = auth.uid(), c.hidden_at is not null,
         coalesce((select jsonb_agg(jsonb_build_object('id', t.id, 'name', t.name) order by t.name)
                     from public.class_comment_tags ct join public.class_tags t on t.id = ct.tag_id
                    where ct.comment_id = c.id), '[]'::jsonb),
         coalesce((select jsonb_agg(jsonb_build_object(
                      'id', r.id, 'resource_type', r.resource_type, 'resource_id', r.resource_id, 'title', r.title_snapshot,
                      'start_seconds', r.start_seconds, 'end_seconds', r.end_seconds, 'excerpt', r.excerpt)
                    order by r.sort_order)
                     from public.class_comment_resources r where r.comment_id = c.id), '[]'::jsonb),
         (select count(*)::int from public.class_post_comments c2
           where c2.post_id = p.id and (c2.hidden_at is null or public.is_teacher()))
  from (select unnest(p_post_ids[1:50]) as pid) ids
  join public.class_posts p on p.id = ids.pid
  cross join lateral (
    select * from public.class_post_comments c0
    where c0.post_id = p.id and (c0.hidden_at is null or public.is_teacher())
    order by c0.seq desc
    limit least(greatest(coalesce(p_per_post, 3), 1), 200)
  ) c
  cross join lateral public.class_public_identity(c.author_user_id) idn
  where public.is_class_member()
    and (p.hidden_at is null or public.is_teacher())
  order by c.post_id, c.seq;
$$;
revoke all on function public.class_comments_for_posts(uuid[], int) from public, anon;
grant execute on function public.class_comments_for_posts(uuid[], int) to authenticated;

