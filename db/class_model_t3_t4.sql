-- 2) Chặng của lớp — CHỈ là lịch nội dung của một lớp vật lý (không phải hệ curriculum):
--    buổi from..to thuộc chặng nào, tên công khai lúc đó, khoá được mở khi vào lớp ở chặng đó.
create table if not exists public.class_stages (
  id           bigint generated by default as identity primary key,
  class_id     uuid not null references public.class_schedule(id) on delete cascade,
  stage_no     int  not null check (stage_no >= 1),
  public_title text not null,
  course_id    uuid references public.edu_courses(id),
  from_session int  not null,
  to_session   int  not null,
  starts_on    date,            -- ngày buổi đầu chặng (suy từ class_sessions, để landing đọc không cần buổi)
  ends_on      date,            -- ngày buổi cuối chặng
  created_at   timestamptz not null default now(),
  unique (class_id, stage_no),
  check (from_session >= 1 and to_session >= from_session)
);
alter table public.class_stages enable row level security;
drop policy if exists cst_read on public.class_stages;
drop policy if exists cst_teacher_write on public.class_stages;
create policy cst_read on public.class_stages for select to anon, authenticated using (true);
create policy cst_teacher_write on public.class_stages for all to authenticated
  using (coalesce(public.is_teacher(), false)) with check (coalesce(public.is_teacher(), false));
