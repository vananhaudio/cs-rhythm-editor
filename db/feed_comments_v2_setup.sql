create table if not exists public.feed_comments (
  id                uuid primary key default gen_random_uuid(),
  seq               bigint generated by default as identity,
  target_kind       text        not null,
  target_id         uuid        not null,
  parent_comment_id uuid        references public.feed_comments(id) on delete cascade,
  author_user_id    uuid        not null references auth.users(id) on delete cascade,
  body              text        not null,
  hidden_at         timestamptz,
  hidden_by         uuid        references auth.users(id) on delete set null,
  edited_at         timestamptz,
  created_at        timestamptz not null default clock_timestamp(),
  constraint feed_comments_kind_check check (target_kind in ('learning_thread', 'teamlab_publication')),
  constraint feed_comments_body_check check (char_length(btrim(body)) between 1 and 2000)
);
create index if not exists feed_comments_target_idx on public.feed_comments (target_kind, target_id, seq);
create index if not exists feed_comments_author_idx on public.feed_comments (author_user_id, created_at desc);
create index if not exists feed_comments_parent_idx on public.feed_comments (parent_comment_id) where parent_comment_id is not null;
alter table public.feed_comments enable row level security;
revoke all on table public.feed_comments from public, anon, authenticated;

-- Chặn nội dung / tài khoản tạm dừng — giống class_ugc_guard_write (Thầy/Admin được miễn). Hàm phụ production có thể chưa có → bỏ qua.
create or replace function public.feed_comment_guard(p_author uuid, p_body text)
returns void language plpgsql stable security definer set search_path = '' as $$
declare v_blocked boolean;
begin
  if exists (select 1 from public.app_users au where au.id = p_author and au.role in ('teacher', 'admin')) then return; end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'edu_students' and column_name = 'blocked_at') then
    execute 'select exists (select 1 from public.edu_students s where s.user_id = $1 and s.blocked_at is not null)' into v_blocked using p_author;
    if v_blocked then raise exception 'account_suspended' using errcode = 'UGC03', hint = 'Tài khoản đang bị tạm dừng tương tác'; end if;
  end if;
  if to_regprocedure('public.class_ugc_text_blocked(text)') is not null then
    execute 'select public.class_ugc_text_blocked($1)' into v_blocked using p_body;
    if v_blocked then raise exception 'ugc_blocked' using errcode = 'UGC01', hint = 'Nội dung chưa phù hợp với quy tắc cộng đồng'; end if;
  end if;
end $$;
revoke all on function public.feed_comment_guard(uuid, text) from public, anon, authenticated;

create or replace function public.feed_comment_add(p_kind text, p_id uuid, p_body text, p_parent uuid default null)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_me uuid := auth.uid(); v_body text := btrim(coalesce(p_body, '')); v_new uuid;
begin
  if v_me is null then raise exception 'FEED_AUTH_REQUIRED' using errcode = '28000'; end if;
  if p_kind not in ('learning_thread', 'teamlab_publication') then raise exception 'FEED_BAD_KIND' using errcode = '22023'; end if;
  if char_length(v_body) not between 1 and 2000 then raise exception 'FEED_BAD_BODY' using errcode = '23514'; end if;
  if not public.feed_target_visible(p_kind, p_id) then raise exception 'FEED_NOT_VISIBLE' using errcode = '42501'; end if;
  if p_parent is not null and not exists (   -- trả lời MỘT cấp: cha phải là bình luận gốc, cùng mục, đang hiển thị
    select 1 from public.feed_comments c
    where c.id = p_parent and c.target_kind = p_kind and c.target_id = p_id and c.parent_comment_id is null
      and (c.hidden_at is null or public.is_teacher())) then
    raise exception 'FEED_BAD_PARENT' using errcode = '23514';
  end if;
  perform public.feed_comment_guard(v_me, v_body);
  insert into public.feed_comments (target_kind, target_id, parent_comment_id, author_user_id, body)
  values (p_kind, p_id, p_parent, v_me, v_body) returning id into v_new;
  return v_new;
end $$;
revoke all on function public.feed_comment_add(text, uuid, text, uuid) from public, anon;
grant execute on function public.feed_comment_add(text, uuid, text, uuid) to authenticated;

-- Danh sách bình luận một mục (thread / publication): cũ → mới theo seq, kèm danh tính công khai. Tối đa p_limit gốc mới nhất + mọi trả lời của chúng.
create or replace function public.feed_comment_list(p_kind text, p_id uuid, p_limit int default 100)
returns table(id uuid, parent_comment_id uuid, body text, created_at timestamptz, edited_at timestamptz,
              author_user_id uuid, author_name text, author_avatar_url text, author_role text, is_mine boolean, is_hidden boolean)
language sql stable security definer set search_path = '' as $$
  with roots as (
    select c.id from public.feed_comments c
    where c.target_kind = p_kind and c.target_id = p_id and c.parent_comment_id is null and (c.hidden_at is null or public.is_teacher())
    order by c.seq desc limit least(greatest(coalesce(p_limit, 100), 1), 200)
  )
  select c.id, c.parent_comment_id, c.body, c.created_at, c.edited_at, c.author_user_id, idn.name, idn.avatar_url, idn.role,
         c.author_user_id = auth.uid(), c.hidden_at is not null
  from public.feed_comments c
  cross join lateral public.class_public_identity(c.author_user_id) idn
  where public.feed_target_visible(p_kind, p_id)
    and p_kind in ('learning_thread', 'teamlab_publication')
    and c.target_kind = p_kind and c.target_id = p_id
    and (c.hidden_at is null or public.is_teacher())
    and (c.id in (select id from roots) or c.parent_comment_id in (select id from roots))
  order by c.seq;
$$;
revoke all on function public.feed_comment_list(text, uuid, int) from public, anon;
grant execute on function public.feed_comment_list(text, uuid, int) to authenticated;

-- Số bình luận theo lô (chỉ mục thấy được). Tối đa 100 mục/lần.
create or replace function public.feed_comment_counts(p_kinds text[], p_ids uuid[])
returns table(target_kind text, target_id uuid, comment_count int)
language sql stable security definer set search_path = '' as $$
  with req as (
    select distinct k.k as kind, i.i as id
    from unnest(p_kinds) with ordinality as k(k, n) join unnest(p_ids) with ordinality as i(i, n) using (n)
    where k.n <= 100
  )
  select r.kind, r.id,
         (select count(*)::int from public.feed_comments c
           where c.target_kind = r.kind and c.target_id = r.id and (c.hidden_at is null or public.is_teacher()))
  from req r
  where r.kind in ('learning_thread', 'teamlab_publication') and public.feed_target_visible(r.kind, r.id);
$$;
revoke all on function public.feed_comment_counts(text[], uuid[]) from public, anon;
grant execute on function public.feed_comment_counts(text[], uuid[]) to authenticated;

-- Sửa bình luận CỦA MÌNH (mọi loại mục). Bài Social: ghi đúng bảng cũ (trigger before_write + ugc guard vẫn chạy).
create or replace function public.feed_comment_edit(p_kind text, p_comment uuid, p_body text)
returns void language plpgsql security definer set search_path = '' as $$
declare v_me uuid := auth.uid(); v_body text := btrim(coalesce(p_body, '')); n int;
begin
  if v_me is null then raise exception 'FEED_AUTH_REQUIRED' using errcode = '28000'; end if;
  if char_length(v_body) not between 1 and 2000 then raise exception 'FEED_BAD_BODY' using errcode = '23514'; end if;
  if p_kind = 'post' then
    update public.class_post_comments c set body = v_body
     where c.id = p_comment and c.author_user_id = v_me and public.class_post_visible(c.post_id);
  elsif p_kind in ('learning_thread', 'teamlab_publication') then
    perform public.feed_comment_guard(v_me, v_body);
    update public.feed_comments c set body = v_body, edited_at = clock_timestamp()
     where c.id = p_comment and c.author_user_id = v_me and c.target_kind = p_kind and public.feed_target_visible(c.target_kind, c.target_id);
  else raise exception 'FEED_BAD_KIND' using errcode = '22023'; end if;
  get diagnostics n = row_count;
  if n = 0 then raise exception 'FEED_NOT_FOUND' using errcode = 'P0002'; end if;
end $$;
revoke all on function public.feed_comment_edit(text, uuid, text) from public, anon;
grant execute on function public.feed_comment_edit(text, uuid, text) to authenticated;

-- Xoá bình luận CỦA MÌNH (kéo theo các trả lời của nó — khoá ngoại cascade, như bảng cũ).
create or replace function public.feed_comment_delete(p_kind text, p_comment uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare v_me uuid := auth.uid(); n int;
begin
  if v_me is null then raise exception 'FEED_AUTH_REQUIRED' using errcode = '28000'; end if;
  if p_kind = 'post' then
    delete from public.class_post_comments c where c.id = p_comment and c.author_user_id = v_me;
  elsif p_kind in ('learning_thread', 'teamlab_publication') then
    delete from public.feed_comments c where c.id = p_comment and c.author_user_id = v_me and c.target_kind = p_kind;
  else raise exception 'FEED_BAD_KIND' using errcode = '22023'; end if;
  get diagnostics n = row_count;
  if n = 0 then raise exception 'FEED_NOT_FOUND' using errcode = 'P0002'; end if;
end $$;
revoke all on function public.feed_comment_delete(text, uuid) from public, anon;
grant execute on function public.feed_comment_delete(text, uuid) to authenticated;

-- Thầy/Admin ẩn / bỏ ẩn bình luận thread/publication (bài Social: dùng class_moderate như cũ).
create or replace function public.feed_comment_hide(p_comment uuid, p_hidden boolean)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_teacher() then raise exception 'Không có quyền' using errcode = '42501'; end if;
  update public.feed_comments set hidden_at = case when p_hidden then now() end, hidden_by = case when p_hidden then auth.uid() end where id = p_comment;
  if not found then raise exception 'FEED_NOT_FOUND' using errcode = 'P0002'; end if;
end $$;
revoke all on function public.feed_comment_hide(uuid, boolean) from public, anon;
grant execute on function public.feed_comment_hide(uuid, boolean) to authenticated;

